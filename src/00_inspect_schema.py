"""D0: inspect the HICO-DET sources and write docs/schema_notes.md.

Downloads (if missing) the HAKE instance-level annotations and the HOI list, and optionally one
zhimeng/hico_det parquet shard (--with-parquet), then reports the facts that decide how CVC1-4 are coded.
"""
from __future__ import annotations

import argparse
import ast
import collections
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from common import RAW, ROOT, load_config  # noqa: E402


def fetch_hake(cfg):
    from huggingface_hub import hf_hub_download
    r = cfg["real"]
    d = RAW / "hake"
    ann = hf_hub_download(r["hake_repo"], r["hake_file"], repo_type="dataset", local_dir=d)
    hoi = hf_hub_download(r["hake_repo"], r["hoi_list_file"], repo_type="dataset", local_dir=d)
    return Path(ann), Path(hoi)


def load_hoi_list(path) -> dict[int, tuple[str, str]]:
    out = {}
    for line in Path(path).read_text().splitlines():
        p = line.split()
        if len(p) >= 3 and p[0].isdigit():
            out[int(p[0])] = (p[1], p[2])
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--with-parquet", action="store_true", help="also profile one zhimeng/hico_det shard")
    a = ap.parse_args()
    cfg = load_config()
    ann_path, hoi_path = fetch_hake(cfg)
    hoi = load_hoi_list(hoi_path)
    ann = json.loads(Path(ann_path).read_text())

    n_img = len(ann)
    pairs_per_img = collections.Counter()
    same_hoi_multi = 0
    persons_per_img = collections.Counter()
    from common import cluster_boxes
    for fn, rec in ann.items():
        labs = rec["labels"]
        pairs_per_img[min(len(labs), 10)] += 1
        c = collections.Counter(l["hoi_id"] for l in labs)
        if any(v > 1 for v in c.values()):
            same_hoi_multi += 1
        hb = [l["human_bbox"] for l in labs if l.get("human_bbox")]
        if hb:
            lab, reps = cluster_boxes(hb, cfg["real"]["thresholds"]["cluster_iou"])
            persons_per_img[min(len(reps), 6)] += 1
        else:
            persons_per_img[0] += 1

    ex_fn = next(iter(ann))
    lines = [
        "# D0 schema notes (generated by src/00_inspect_schema.py)",
        "",
        "## Sources",
        f"- **Annotations**: `{cfg['real']['hake_repo']}` / `{cfg['real']['hake_file']}` (HAKE release of HICO-DET train).",
        f"  {n_img:,} images. Dict `filename -> {{labels: [...], path_prefix, dataset}}`.",
        "  Each label is one annotated human-object pair: `hoi_id` (1-based into `hico_hoi_list.txt`),",
        "  `human_bbox` and `object_bbox` in **xyxy pixels**, `width`, `height`, plus HAKE part states (unused).",
        f"- **HOI list**: {len(hoi)} (object, verb) categories, e.g. 496 = {hoi.get(496)}.",
        f"- **Images**: `{cfg['real']['image_repo']}` stores `HICO_train2015_XXXXXXXX.jpg` individually (part01..part08),",
        "  so only candidate images need downloading.",
        "",
        "## Facts that decide the CVC coding",
        f"- Images with >1 pair of the *same* HOI category: {same_hoi_multi:,}. These multi-person pairs are",
        "  **lost** in `zhimeng/hico_det`, whose `objects` field keeps one box pair per HOI id (verified on a test shard,",
        "  bbox order there is [x1, x2, y1, y2]). That is why the HAKE file is the annotation source.",
        "- The same physical person is boxed separately for every HOI row, with slightly different coordinates, so",
        "  person and object *instances* are recovered by clustering boxes at IoU >= "
        f"{cfg['real']['thresholds']['cluster_iou']}.",
        "- HICO-DET boxes only people who take part in an annotated interaction. Bystanders are not boxed, so",
        "  CVC1 also needs a detector pass (see `01_build_real.py`).",
        "- `no_interaction` rows are explicit negatives: a person boxed with `no_interaction` for an object is",
        "  evidence that they do *not* use it, and is allowed for the distractor in CVC4.",
        "",
        "## Annotated person instances per image (after clustering)",
        "| persons | images |", "|---|---|",
        *[f"| {k}{'+' if k == 6 else ''} | {v:,} |" for k, v in sorted(persons_per_img.items())],
        "",
        "## Example record",
        "```json",
        json.dumps({ex_fn: {**ann[ex_fn], "labels": ann[ex_fn]["labels"][:2]}}, indent=1)[:1500],
        "```",
    ]

    if a.with_parquet:
        import pyarrow.parquet as pq
        from huggingface_hub import hf_hub_download
        p = hf_hub_download("zhimeng/hico_det", "data/test-00000-of-00004.parquet", repo_type="dataset",
                            local_dir=RAW / "hico")
        t = pq.read_table(p, columns=["objects"]).to_pylist()
        dup = sum(1 for r in t if len({o["id"] for o in ast.literal_eval(r["objects"])}) != len(ast.literal_eval(r["objects"])))
        lines += ["", f"## zhimeng/hico_det shard check", f"- rows {len(t)}, rows with a repeated HOI id: {dup} (expected 0: one pair per HOI)"]

    out = ROOT / "docs" / "schema_notes.md"
    out.parent.mkdir(exist_ok=True)
    out.write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
